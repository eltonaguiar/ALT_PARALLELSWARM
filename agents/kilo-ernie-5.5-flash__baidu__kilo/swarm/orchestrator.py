"""
orchestrator.py — plan → gate → dispatch → collect.

Reads tasks/<task>/task.json. For each worktree it:
  1. checks the model is reachable (probe.json, or a live ping if --live)
  2. if reachable, dispatches the worktree's prompt (optionally prepending shared
     context files such as web-research notes) to the model via llm_router
  3. writes the reply to files/<output_file> and a phase marker
  4. records status in _ORCHESTRATION/phase_state.json

Concurrency and daily caps are enforced by the shared UsageTracker, so free keys
stay within budget. Unreachable models are marked "skipped" and the run continues
(degrade gracefully) — the lead agent can hand their slice to a backup.

Usage:
  python -m swarm.orchestrator --task SNC_DISC_RESEARCH            # run all
  python -m swarm.orchestrator --task SNC_DISC_RESEARCH --only WT2 # one worktree
  python -m swarm.orchestrator --task SNC_DISC_RESEARCH --dry-run  # show plan only
"""
from __future__ import annotations

import argparse
import json
import time
from concurrent.futures import ThreadPoolExecutor, as_completed
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

from .llm_router import LLMRouter, load_registry
from .usage_tracker import UsageTracker
from .capability_probe import PROBE_PATH

ROOT = Path(__file__).resolve().parent.parent
TASKS = ROOT / "tasks"


def _now() -> str:
    return datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")


def _reachable(model_key: str) -> bool:
    if not PROBE_PATH.exists():
        return True  # no probe yet: assume reachable, router will fail loud
    data = json.loads(PROBE_PATH.read_text())
    for r in data.get("results", []):
        if r["model"] == model_key:
            return bool(r["ok"])
    return True


def run_worktree(wt_cfg: dict, task_dir: Path, shared_ctx: str, tracker: UsageTracker) -> dict[str, Any]:
    model = wt_cfg.get("model")
    slug = wt_cfg.get("slug") or (model or "").replace("/", "-").replace(":", "-").lower()
    wt_dir = task_dir / "worktrees" / f"{wt_cfg['id']}_{slug}"
    out_file = wt_cfg.get("output_file", "files/output.md")
    out_path = wt_dir / out_file
    status = {"id": wt_cfg["id"], "model": model, "status": "unknown",
              "output": str(out_path.relative_to(ROOT)) if out_path.exists() else str(out_path)}

    if wt_cfg.get("skip_dispatch") or not model:
        status["status"] = "skipped-lead"
        _write_phase(wt_dir, 1, "Lead worktree — authored directly by the lead agent (not dispatched).")
        return status

    if not _reachable(model):
        status["status"] = "skipped-unreachable"
        _write_phase(wt_dir, 1, f"Skipped: model {model} not reachable (see probe.json).")
        return status

    # build the prompt: TASK FIRST (so models don't anchor on the broad context),
    # then reference context clearly labelled as background.
    prompt = wt_cfg.get("prompt") or wt_cfg.get("goal", "")
    ctx_files = wt_cfg.get("context_files", [])
    parts = [f"## Your task\n\n{prompt}"]
    if shared_ctx:
        parts.append("\n## Reference context (background only — do NOT restate it; "
                     "use it to inform your answer)\n\n" + shared_ctx)
    for cf in ctx_files:
        p = task_dir / cf
        if p.exists():
            parts.append(f"\n## Context file: {cf}\n\n{p.read_text()}")
    full_prompt = "\n".join(parts)

    _write_phase(wt_dir, 1, f"Phase 1 started: calling {model}.")

    router = LLMRouter(tracker=tracker)
    t0 = time.time()
    try:
        out = router.chat(model, [
            {"role": "system", "content": (
                "You are a precise ServiceNow technical writer. Output ONLY the requested "
                "section as GitHub-flavored Markdown. Do NOT summarize the shared context, do NOT "
                "ask questions, and do NOT add meta commentary. Start with one H1 title, then "
                "specific H2/H3 sections. Be concrete: name exact menu paths, table names, and "
                "system properties where relevant. If you are unsure, say so explicitly."
            )},
            {"role": "user", "content": full_prompt},
        ], temperature=wt_cfg.get("temperature", 0.3),
            max_tokens=wt_cfg.get("max_tokens", 1800),
            timeout=wt_cfg.get("timeout", 240))
        text = out["text"]
    except Exception as e:  # noqa: BLE001
        status["status"] = "error"
        status["error"] = str(e)[:400]
        _write_phase(wt_dir, 1, f"Phase 1 FAILED calling {model}: {e}")
        return status

    out_path.parent.mkdir(parents=True, exist_ok=True)
    header = (f"<!-- generated by orchestrator.py | model={model} | "
              f"latency={time.time()-t0:.1f}s | {_now()} -->\n\n")
    out_path.write_text(header + text)
    status["status"] = "done"
    status["latency_s"] = round(time.time() - t0, 2)
    _write_phase(wt_dir, 2, f"Phase 2 complete: output written to {out_file}.")
    return status


def _write_phase(wt_dir: Path, n: int, text: str) -> None:
    (wt_dir / "phases").mkdir(parents=True, exist_ok=True)
    (wt_dir / "phases" / f"phase{n}.md").write_text(
        f"# Phase {n} — {_now()}\n\n{text}\n")


def main() -> None:
    ap = argparse.ArgumentParser(description="Run the swarm")
    ap.add_argument("--task", required=True)
    ap.add_argument("--only", default=None, help="run a single worktree id, e.g. WT2")
    ap.add_argument("--dry-run", action="store_true")
    ap.add_argument("--live", action="store_true", help="ping models live (ignore probe cache)")
    ap.add_argument("--shared-context", default=None, help="file with shared context text")
    args = ap.parse_args()

    task_dir = TASKS / args.task
    cfg = json.loads((task_dir / "task.json").read_text())
    wts = cfg["worktrees"]
    if args.only:
        wts = [w for w in wts if w["id"] == args.only]

    shared_ctx = ""
    if args.shared_context:
        scp = Path(args.shared_context)
        if scp.exists():
            shared_ctx = scp.read_text()

    if args.dry_run:
        print(f"DRY RUN — {len(wts)} worktree(s):")
        for w in wts:
            model = w.get("model") or "(lead)"
            print(f"  {w['id']:5s} {model:40s} reachable={_reachable(w['model']) if w.get('model') else 'n/a'}")
        return

    if args.live:
        # refresh the probe for these models first
        from .capability_probe import probe_one
        reg = load_registry()
        tracker0 = UsageTracker()
        for w in wts:
            r = probe_one(w["model"], reg, tracker0)
            print(f"  probe {w['model']}: {'OK' if r['ok'] else 'FAIL ' + (r['error'] or '')}")

    tracker = UsageTracker()
    state_path = task_dir / "_ORCHESTRATION" / "phase_state.json"
    state_path.parent.mkdir(parents=True, exist_ok=True)

    results = []
    # run worktrees in parallel; the tracker caps per-provider concurrency
    with ThreadPoolExecutor(max_workers=min(6, len(wts))) as ex:
        futs = {ex.submit(run_worktree, w, task_dir, shared_ctx, tracker): w for w in wts}
        for fut in as_completed(futs):
            st = fut.result()
            results.append(st)
            print(f"[{st['status']:18s}] {st['id']} ({st['model']})")

    state = {
        "task": args.task,
        "run_at": _now(),
        "worktrees": results,
        "usage": tracker.report(),
    }
    state_path.write_text(json.dumps(state, indent=2))
    done = sum(1 for r in results if r["status"] == "done")
    print(f"\n{done}/{len(results)} worktrees completed. State → {state_path}")


if __name__ == "__main__":
    main()